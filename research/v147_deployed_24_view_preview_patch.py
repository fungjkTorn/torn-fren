def build_candidate(html):
    content=exact_replace(html,OLD_HEADER,NEW_HEADER)
    content=exact_replace(content,OLD_FIELDS,NEW_FIELDS)
    content=exact_replace(
        content,'const tbody=document.getElementById("rows"), state=document.getElementById("state");',
        'const tbody=document.getElementById("rows"), state=document.getElementById("state");\n'+TICKER)
    content=exact_replace(content,'function paint(rows){\n tbody.replaceChildren();',
        'function paint(rows){\n betaRows=Array.isArray(rows)?rows:[];\n tbody.replaceChildren();')
    content=exact_replace(content,
        'if(["departure","arrival","valid_until"].includes(field))v=when(v);',
        'if(["departure","arrival","valid_until"].includes(field))v=when(v);\n'
        '   if(field==="leave_in")v="—";')
    content=exact_replace(content,
        'if(field==="status"){v=item.actionable?"Ready · experimental":v;td.className=item.actionable?"good":"warn";}',
        'if(field==="status"){v=item.actionable?"Research signal · unverified":v;td.className="warn";}')
    content=exact_replace(content,
        'state.textContent="Last refreshed: "+new Date().toLocaleTimeString()+". "+rows.filter(x=>x.actionable).length+" actionable experimental proposals out of "+rows.length+" snapshot rows.";',
        'tickBetaRows();\n state.textContent="Last refreshed: "+new Date().toLocaleTimeString()+". "+rows.filter(x=>x.actionable).length+" provisional research signals out of "+rows.length+" rows; no verified flight guarantee.";')
    content=exact_replace(content,
        'refresh();setInterval(refresh,30000);',
        'refresh();setInterval(refresh,30000);setInterval(tickBetaRows,1000);')
    content=exact_replace(content,
        'if(!snap||!snap.actionable||!ch.scales.x)return;',
        'if(!snap||!snap.actionable||!ch.scales.x||snap.valid_until<=Date.now()/1000||snap.departure<=Date.now()/1000)return;')
    # A refresh error should not leave a previous row falsely "ready";
    # subsequent one-second ticks independently revoke expired snapshots.
    content=exact_replace(content,
        'if(!response.ok){state.textContent=response.status===404?"Experimental preview is not enabled.":"Snapshot endpoint unavailable (HTTP "+response.status+").";return;}',
        'if(!response.ok){state.textContent="Snapshot refresh failed (HTTP "+response.status+"). Existing rows require recheck.";tickBetaRows();return;}')
    if content==html:
        raise AssertionError("unmodified candidate")
    return content


def stage(source_dir,output_dir):
    src=Path(source_dir).resolve(strict=True)
    out=Path(output_dir).resolve(strict=False)
    if src==out or src in out.parents or out in src.parents:
        raise ValueError("must use separate preview directory")
    if out.exists() and (out.is_symlink() or any(out.iterdir())):
        raise ValueError("preview output must be empty, non-symlink")
    if str(out).startswith(("/opt/torn-fren/","/var/lib/torn-fren-v38/")):
        raise ValueError("writing into deployed service paths prohibited")
    contents={}
    for name,digest in EXPECTED.items():
        f=src/name
        if not f.is_file() or f.is_symlink():
            raise ValueError(f"missing or symlinked source: {name}")
        binary=f.read_bytes()
        if hashlib.sha256(binary).hexdigest()!=digest:
            raise ValueError(f"deployed source hash differs: {name}")
        contents[name]=binary
    html=contents["experimental.html"].decode("utf-8")
    patched=build_candidate(html).encode("utf-8")
    out.mkdir(parents=True,exist_ok=True)
    for name,blob in contents.items():
        (out/name).write_bytes(patched if name=="experimental.html" else blob)
    return {
        "research_preview_only":True,
        "files":["app.py","experimental.html","index.html"],
        "original_graph_source_byte_identical":(
            (out/"index.html").read_bytes()==contents["index.html"]),
        "deployed_server_source_byte_identical":(
            (out/"app.py").read_bytes()==contents["app.py"]),
        "live_site_modified":False,
        "experimental_html_preview_sha256":hashlib.sha256(patched).hexdigest(),
    }


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source_directory",type=Path)
    parser.add_argument("preview_output_directory",type=Path)
    args=parser.parse_args()
    print(stage(args.source_directory,args.preview_output_directory))


if __name__=="__main__":
    main()
